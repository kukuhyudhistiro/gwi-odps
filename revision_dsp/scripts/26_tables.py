def table(path: Path, cols):
    with open(path, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    cols = [c for c in cols if rows and c in rows[0]]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        lines.append("| " + " | ".join(str(r.get(c, "")) for c in cols) + " |")
    return lines


def main():
    args = parser(__doc__).parse_args()
    cfg, _ = setup(args)
    rd = C.results_dir(cfg)
    out = ["# Revision tables (generated by scripts/26_tables.py)", ""]
    for title, rel, cols in SECTIONS:
        p = rd / rel
        out += [f"## {title}", f"`{rel}`", ""]
        out += table(p, cols) if p.exists() else ["(not run yet)"]
        out.append("")
    (rd / "TABLES.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"  -> {rd / 'TABLES.md'}")


if __name__ == "__main__":
    main()
